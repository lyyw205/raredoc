async function main() {
  const kkey = (s: string) => s.replace(/[\s　]/g, "");
  const lcs = await prisma.card.findMany({
    where: { supertype: { in: ["Trainer", "Energy"] }, AND: [{ locales: { some: { region: "JP" } } }, { locales: { some: { region: "KR" } } }] },
    select: { locales: { select: { region: true, name: true } } },
  });
  // ja → (ko → 빈도)
  const freq = new Map<string, Map<string, number>>();
  for (const lc of lcs) {
    const jas = [...new Set(lc.locales.filter((l) => l.region === "JP").map((l) => kkey(l.name)))];
    const kos = [...new Set(lc.locales.filter((l) => l.region === "KR").map((l) => kkey(l.name)))];
    for (const ja of jas) {
      if (!freq.has(ja)) freq.set(ja, new Map());
      for (const ko of kos) freq.get(ja)!.set(ko, (freq.get(ja)!.get(ko) ?? 0) + 1);
    }
  }
  let maj = 0, neu = 0;
  const flags: string[] = [];
  for (const [ja, ko] of Object.entries(MC_PAIRS)) {
    const f = freq.get(kkey(ja));
    if (!f || f.size === 0) { neu++; flags.push(`NEW      ${ja} = ${ko} (DB 무데이터 — 수동확정)`); continue; }
    const sorted = [...f.entries()].sort((a, b) => b[1] - a[1]);
    const top = sorted[0];
    if (top[0] === kkey(ko) && (sorted.length === 1 || top[1] > (sorted[1]?.[1] ?? 0))) maj++;
    else if (f.has(kkey(ko))) flags.push(`MIN      ${ja} = ${ko} (다수결은 ${top[0]}×${top[1]}, 제안쌍 ×${f.get(kkey(ko))})`);
    else flags.push(`CONFLICT ${ja} = ${ko} (DB 다수결: ${sorted.slice(0, 3).map(([k, v]) => `${k}×${v}`).join(", ")})`);
  }
  console.log(`총 ${Object.keys(MC_PAIRS).length}쌍 | 다수결 일치 ${maj} · 무데이터 ${neu} · 플래그 ${flags.filter((f) => !f.startsWith("NEW")).length}`);
  console.log(flags.join("\n"));
  await prisma.$disconnect();
}

main().catch((e) => { console.error(e); process.exit(1); });
